#!/usr/bin/env python3
"""Extract user-facing SwiftUI string literals into a Localizable.strings inventory.

SwiftUI's Text, Button, Toggle, Picker, Label, navigationTitle and friends take a
LocalizedStringKey, so a literal written in a view is ALREADY a localization key --
it just resolves to itself while no catalog exists. This builds the inventory of
those keys so they can be translated without touching a single call site.

Deliberately conservative: it only matches the view initializers whose first
argument is known to be a LocalizedStringKey. Strings assembled at runtime, model
`detail:` text, and error messages are not LocalizedStringKey and need
`String(localized:)` at their definition instead -- they are reported separately
rather than silently skipped.

Usage: extract-strings.py [--write Resources/en.lproj/Localizable.strings]
"""
import argparse
import pathlib
import re
import sys

# First argument of these is a LocalizedStringKey in SwiftUI, or an explicitly
# localized String. Model-layer copy uses `String(localized:)` because it is not
# built inside a view and has no LocalizedStringKey to resolve against.
LOCALIZED_FIRST_ARG = [
    r'String\(localized:\s*', r'NSLocalizedString\(',
    r'Text\(', r'Button\(', r'Toggle\(', r'Label\(', r'Picker\(', r'Stepper\(',
    r'TextField\(', r'SecureField\(', r'navigationTitle\(', r'Link\(',
    r'DisclosureGroup\(', r'Section\(', r'Menu\(', r'\.help\(',
    r'\.accessibilityLabel\(', r'\.accessibilityHint\(',
]
# A literal with no interpolation: interpolated strings need their own treatment.
PLAIN = r'"((?:[^"\\\n]|\\.)+)"'
PATTERN = re.compile("(?:" + "|".join(LOCALIZED_FIRST_ARG) + r")\s*" + PLAIN)
INTERPOLATED = re.compile("(?:" + "|".join(LOCALIZED_FIRST_ARG) + r')\s*"[^"\n]*\\\(')


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", help="Write a .strings file to this path.")
    parser.add_argument("--root", default="Sources", help="Directory to scan.")
    args = parser.parse_args()

    keys = {}
    interpolated = 0
    for path in sorted(pathlib.Path(args.root).rglob("*.swift")):
        text = path.read_text(encoding="utf-8")
        interpolated += len(INTERPOLATED.findall(text))
        for line_number, line in enumerate(text.splitlines(), start=1):
            for match in PATTERN.finditer(line):
                key = match.group(1)
                if len(key) < 2 or key.startswith("/") or key.startswith("~"):
                    continue  # paths and single characters are not copy
                keys.setdefault(key, []).append(f"{path}:{line_number}")

    print(f"{len(keys)} localizable keys across {args.root}", file=sys.stderr)
    print(f"{interpolated} interpolated literals need String(localized:) with arguments", file=sys.stderr)

    if not args.write:
        for key in sorted(keys):
            print(key)
        return 0

    destination = pathlib.Path(args.write)
    destination.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "/* Nuke Sweep -- base English strings.",
        "   Generated by scripts/extract-strings.py; see docs/LOCALIZATION.md.",
        "   Keys are the English source text, which is how SwiftUI resolves a",
        "   LocalizedStringKey when no translation exists. Edit translations in the",
        "   other .lproj directories, not here. */",
        "",
    ]
    for key in sorted(keys):
        where = keys[key][0]
        escaped = key.replace('"', '\\"')
        lines.append(f"/* {where} */")
        lines.append(f'"{escaped}" = "{escaped}";')
        lines.append("")
    destination.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {destination}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
